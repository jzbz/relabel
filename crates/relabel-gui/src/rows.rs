//! The boundary between the document and the toolkit: one element becomes one
//! row, and that is the only conversion there is.
//!
//! # Why this is a trait and a macro rather than a function
//!
//! Slint generates a fresh Rust type for every component it compiles, so the
//! `ElRow` the application gets and the `ElRow` a test probe gets are different
//! types with identical fields. The wiring in [`crate::canvas`] must be the
//! same code in both, or the tests would be exercising a copy of it, so the
//! row type and the window type are named by a trait and the two-line
//! implementation is generated by [`impl_canvas_host!`].

use crate::doc::Shown;
use relabel_render::media::Keepout;

/// The tone a frame is drawn in, as a small integer the `.slint` can compare.
///
/// Deliberately not an exported Slint enum: the canvas must not grow a copy of
/// `Keepout` that a later variant would silently fall out of. A number it does
/// not know draws as clear, and the sentence still says what is wrong.
pub fn keepout_ordinal(off_canvas: bool, k: Option<Keepout>) -> i32 {
    if off_canvas {
        // Its own number rather than a keep-out's: the canvas only asks
        // whether this is zero, and the sentence carries which fault it is.
        return 5;
    }
    match k {
        None => 0,
        Some(Keepout::Repeated) => 1,
        Some(Keepout::Tail) => 2,
        Some(Keepout::Inset) => 3,
        Some(Keepout::Shape) => 4,
    }
}

/// One row of the canvas model, whichever compiled component it belongs to.
///
/// `PartialEq` so the canvas can write only the rows an outcome changed.
pub trait CanvasRow: Clone + PartialEq + 'static {
    /// `clear` is [`crate::geom::clearances`]'s answer for this frame.
    fn of(s: &Shown, clear: [i32; 4]) -> Self;
}

/// The canvas's half of a window: the properties it is pushed and the callbacks
/// it sends back.
pub trait CanvasHost: slint::ComponentHandle + 'static {
    type Row: CanvasRow;

    fn set_rows(&self, rows: slint::ModelRc<Self::Row>);
    fn set_selected(&self, id: i32);
    fn set_zoom(&self, zoom: i32);
    fn set_dots_x(&self, dots: i32);
    fn set_dots_y(&self, dots: i32);
    fn set_plane(&self, plane: slint::Image);
    fn set_plane_px_w(&self, px: i32);
    fn set_plane_px_h(&self, px: i32);
    fn set_status(&self, status: slint::SharedString);

    fn on_select(&self, f: impl FnMut(i32) + 'static);
    fn on_begin_move(&self, f: impl FnMut(i32) + 'static);
    fn on_move_to(&self, f: impl FnMut(i32, i32, i32) + 'static);
    fn on_end_move(&self, f: impl FnMut(bool) + 'static);
    fn on_nudge(&self, f: impl FnMut(i32, i32, i32, bool) + 'static);
    fn on_set_say(&self, f: impl FnMut(i32, slint::SharedString) + 'static);
    fn on_undo(&self, f: impl FnMut() + 'static);
    fn on_redo(&self, f: impl FnMut() + 'static);
}

/// Bind a compiled window and its row struct to the wiring in
/// [`crate::canvas`]. Called once in this crate for the application window and
/// once in each test file for its probe.
#[macro_export]
macro_rules! impl_canvas_host {
    ($win:ty, $row:path) => {
        impl $crate::rows::CanvasRow for $row {
            fn of(s: &$crate::doc::Shown, clear: [i32; 4]) -> $row {
                $row {
                    id: s.id as i32,
                    x: s.x,
                    y: s.y,
                    w: s.w,
                    h: s.h,
                    say: s.say.as_str().into(),
                    locked: s.locked,
                    keepout: $crate::rows::keepout_ordinal(s.off_canvas, s.keepout),
                    clear_left: clear[0],
                    clear_right: clear[1],
                    clear_up: clear[2],
                    clear_down: clear[3],
                }
            }
        }

        impl $crate::rows::CanvasHost for $win {
            type Row = $row;

            fn set_rows(&self, rows: slint::ModelRc<$row>) {
                <$win>::set_rows(self, rows)
            }
            fn set_selected(&self, id: i32) {
                <$win>::set_selected(self, id)
            }
            fn set_zoom(&self, zoom: i32) {
                <$win>::set_zoom(self, zoom)
            }
            fn set_dots_x(&self, dots: i32) {
                <$win>::set_dots_x(self, dots)
            }
            fn set_dots_y(&self, dots: i32) {
                <$win>::set_dots_y(self, dots)
            }
            fn set_plane(&self, plane: slint::Image) {
                <$win>::set_plane(self, plane)
            }
            fn set_plane_px_w(&self, px: i32) {
                <$win>::set_plane_px_w(self, px)
            }
            fn set_plane_px_h(&self, px: i32) {
                <$win>::set_plane_px_h(self, px)
            }
            fn set_status(&self, status: slint::SharedString) {
                <$win>::set_status(self, status)
            }
            fn on_select(&self, f: impl FnMut(i32) + 'static) {
                <$win>::on_select(self, f)
            }
            fn on_begin_move(&self, f: impl FnMut(i32) + 'static) {
                <$win>::on_begin_move(self, f)
            }
            fn on_move_to(&self, f: impl FnMut(i32, i32, i32) + 'static) {
                <$win>::on_move_to(self, f)
            }
            fn on_end_move(&self, f: impl FnMut(bool) + 'static) {
                <$win>::on_end_move(self, f)
            }
            fn on_nudge(&self, f: impl FnMut(i32, i32, i32, bool) + 'static) {
                <$win>::on_nudge(self, f)
            }
            fn on_set_say(&self, f: impl FnMut(i32, slint::SharedString) + 'static) {
                <$win>::on_set_say(self, f)
            }
            fn on_undo(&self, f: impl FnMut() + 'static) {
                <$win>::on_undo(self, f)
            }
            fn on_redo(&self, f: impl FnMut() + 'static) {
                <$win>::on_redo(self, f)
            }
        }
    };
}

/// The view's half of a window: the pan and readout it is pushed, what it reads
/// back from the layout, and the commands it sends.
///
/// A trait of its own beside `InsHost`, for that trait's reason: the canvas probes
/// have no view, compile untouched, and keep the zoom their tests are stated at.
pub trait ViewHost: CanvasHost {
    fn set_pan_x(&self, px: i32);
    fn set_pan_y(&self, px: i32);
    /// The scroll bars' extent in device pixels: the pans the view allows, plus one
    /// view.
    fn set_scene_x(&self, px: i32);
    fn set_scene_y(&self, px: i32);
    fn set_scene_w(&self, px: i32);
    fn set_scene_h(&self, px: i32);
    fn set_zoom_says(&self, says: slint::SharedString);
    /// The port in whole device pixels, less the half pixel the dot grid's anchor
    /// can add. Read when needed rather than pushed, because the layout decides it.
    fn get_view_px_w(&self) -> i32;
    fn get_view_px_h(&self) -> i32;
    /// True from a press on an element to its release or cancel, written by the
    /// element's own TouchArea.
    fn get_pointer_down(&self) -> bool;

    fn on_zoom_step(&self, f: impl FnMut(i32) + 'static);
    fn on_zoom_one(&self, f: impl FnMut() + 'static);
    fn on_zoom_fit(&self, f: impl FnMut() + 'static);
    fn on_zoom_wheel(&self, f: impl FnMut(f32, f32, f32) + 'static);
    fn on_pan_by(&self, f: impl FnMut(f32, f32) + 'static);
    fn on_pan_to(&self, f: impl FnMut(i32, i32) + 'static);
    fn on_view_resized(&self, f: impl FnMut() + 'static);
}

