/// Linear light for an sRGB code, `0.0` to `1.0`.
#[inline]
pub fn to_linear(code: u8) -> f32 {
    TO_LINEAR[usize::from(code)]
}

/// The sRGB code nearest a linear value in linear light. Values outside `0.0`
/// to `1.0` clamp to the ends.
#[inline]
pub fn from_linear(v: f32) -> u8 {
    MIDPOINTS.partition_point(|&m| m <= v) as u8
}
